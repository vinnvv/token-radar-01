// Token Radar model radar-2: one snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot watchlist and every other
// clean pre-token protocol the radar can rank. A protocol is pre-token
// when its record carries no token (no market cap, no CoinGecko id, no
// symbol). Wrapped, staked, bridged and exchange products are set aside,
// because they are not a protocol waiting for a launch of its own.
//
// Implied value is calibrated from the snapshot itself, not from a flat
// multiple. For each category, the live-token protocols in the snapshot
// give a market multiple (market cap divided by TVL), winsorised to
// 0.01..2 so one outlier cannot set a category. The category multiple
// is the median of those, shrunk toward the global median so a category
// with few live protocols does not swing the board, then clamped to
// 0.08..0.45; a category with fewer than three live protocols takes the
// global multiple outright. A Dex therefore earns a higher multiple
// than a lending protocol, because the market in this snapshot values
// Dexes that way.
//
//   base         = tvl_usd x category_multiple
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x 0.8
//   maturity     = 0.65 + 0.35 x sqrt(min(age_days, 1095) / 1095)
//   chainMult    = 1 + 0.02 x min(chains - 1, 5)
//   implied      = max(1, round(base x growthMult x maturity x chainMult))
//
// Age is days since first listing; unknown age uses 365 days. No
// protocol name is ever special-cased: one function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

